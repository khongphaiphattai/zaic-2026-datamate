"""
engine.py: In-Memory DuckDB Engine with Automated Self-Correction Loop
and Gate 2 Sanity & Refusal Verification.
"""

from __future__ import annotations

import logging
from collections.abc import Callable
from dataclasses import dataclass

import duckdb
import pandas as pd

logger = logging.getLogger(__name__)


@dataclass
class ExecutionResult:
    success: bool
    df_result: pd.DataFrame | None = None
    error_message: str | None = None
    is_refused: bool = False
    refusal_reason: str | None = None
    retry_count: int = 0


class DuckDBAgentEngine:
    """In-memory DuckDB sandbox equipped with automated SQL error self-correction

    and execution sanity checking.
    """

    def __init__(
        self,
        df: pd.DataFrame | None = None,
        table_name: str = "dataset",
        con: duckdb.DuckDBPyConnection | None = None,
    ):
        self.df = df
        self.table_name = table_name
        if con is not None:
            self.con = con
        else:
            self.con = duckdb.connect(database=":memory:")
            if df is not None:
                self.con.register(table_name, df)

    def execute_query(self, sql: str) -> tuple[bool, pd.DataFrame | None, str | None]:
        """Run SQL safely against the in-memory registered DataFrame."""
        try:
            # Clean common markdown formatting if present
            cleaned_sql = sql.strip().replace("```sql", "").replace("```", "").strip()
            res_df = self.con.execute(cleaned_sql).fetchdf()
            return True, res_df, None
        except Exception as e:
            return False, None, str(e)

    def run_with_self_correction(
        self,
        initial_sql: str,
        sql_generator: Callable[[str, str, int], str],
        max_retries: int = 2,
    ) -> ExecutionResult:
        """Execute SQL with an automated self-correction feedback loop.

        Args:
            initial_sql: The first SQL query generated by the agent.
            sql_generator: Callback function (current_sql, error_msg, attempt) -> new_sql.
            max_retries: Maximum number of correction attempts.
        """
        current_sql = initial_sql
        last_error: str | None = None

        for attempt in range(max_retries + 1):
            success, res_df, err = self.execute_query(current_sql)
            if success:
                # Passed execution -> Proceed to Gate 2 Sanity Check
                is_refused, reason = self._sanity_check(res_df)
                return ExecutionResult(
                    success=True,
                    df_result=res_df,
                    is_refused=is_refused,
                    refusal_reason=reason,
                    retry_count=attempt,
                )
            else:
                last_error = err
                logger.warning(
                    "SQL execution failed (attempt %d/%d): %s",
                    attempt + 1,
                    max_retries + 1,
                    err,
                )
                if attempt < max_retries:
                    # Self-correction: Generate refined SQL using the error feedback
                    current_sql = sql_generator(current_sql, err, attempt + 1)

        # All retries failed -> Refuse safely rather than returning hallucinated data
        return ExecutionResult(
            success=False,
            error_message=last_error,
            is_refused=True,
            refusal_reason=f"Thực thi SQL thất bại sau {max_retries + 1} lần thử: {last_error}",
            retry_count=max_retries,
        )

    def _sanity_check(self, res_df: pd.DataFrame | None) -> tuple[bool, str | None]:
        """Gate 2 (Strict-Refusal-Eval): Check if result is empty, all-null, or ambiguous."""
        if res_df is None or res_df.empty:
            return (
                True,
                "Dữ liệu trả về rỗng, không tìm thấy bản ghi thỏa mãn điều kiện.",
            )

        # If scalar result is NaN/None
        if res_df.shape == (1, 1):
            val = res_df.iloc[0, 0]
            if pd.isna(val) or val is None:
                return (
                    True,
                    "Kết quả tính toán trả về giá trị NULL hoặc không xác định.",
                )

        return False, None
